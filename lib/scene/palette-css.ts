import { contrast, darkenTo, lightenTo, mix, rgba } from "./color"
import { CP_COLORS, CP_COLOR_NAMES, PALETTES, type Palette } from "./palettes"

/**
 * Builds app/palettes.css from the theme table. The file is committed, `npm run build:palettes` rewrites it, and a unit test
 * compares the two, so the stylesheet can never disagree with lib/scene/palettes.ts.
 *
 * It holds three things:
 *  1. The eight genre colours (--c-*) and the code colours (--tok-*), for both the dark and the light theme.
 *  2. One block per theme that changes the primary, signal and danger colours and tints the ink.
 *  3. Nothing for Night City's surfaces: that is the base look in globals.css.
 */

export const DARK = {
  background: "#090b12",
  card: "#0f121b",
  popover: "#0b0e16",
  secondary: "#161a26",
  muted: "#121622",
  accent: "#1b2030",
  border: "#232838",
  input: "#2b3248",
  sidebar: "#05060b",
  "sidebar-accent": "#121623",
  "sidebar-border": "#1a1f2d",
  bubble: "#101728",
  code: "#070910",
} as const

/** How far each dark surface leans toward a theme's primary colour. */
export const TINT: Record<keyof typeof DARK, number> = {
  background: 0.05,
  card: 0.06,
  popover: 0.05,
  secondary: 0.07,
  muted: 0.06,
  accent: 0.09,
  border: 0.1,
  input: 0.12,
  sidebar: 0.04,
  "sidebar-accent": 0.07,
  "sidebar-border": 0.08,
  bubble: 0.08,
  code: 0.04,
}

/** The grey used for secondary text in Night City. Themes that tint the surfaces lighten it just enough to stay readable on them. */
export const MUTED_FOREGROUND = "#8d96ae"

export const LIGHT = { background: "#eceff5", card: "#f7f8fb", code: "#e6eaf2", ink: "#10131c" } as const
export const INK = "#0a0b10"

/** What a theme resolves to in each mode: the same numbers the stylesheet gets, exposed so tests can check them. */
export function resolve(p: Palette) {
  const surfaces = Object.fromEntries((Object.keys(DARK) as (keyof typeof DARK)[]).map((k) => [k, mix(DARK[k], p.primary, TINT[k])])) as Record<keyof typeof DARK, string>
  const dark = {
    surfaces,
    mutedForeground: lightenTo(MUTED_FOREGROUND, surfaces.accent, 4.9),
    /** The signal colour as text and icons: lightened just enough to read on a card. Rings and glows keep the pure colour. */
    signal: lightenTo(p.signal, surfaces.card, 4.6),
    heat: lightenTo(p.heat, surfaces.card, 4.8),
    link: lightenTo(mix(p.signal, "#ffffff", 0.25), surfaces.background, 7),
    grid: rgba(mix(p.signal, "#8296dc", 0.65), 0.06),
  }
  const light = {
    signal: darkenTo(p.signal, LIGHT.background, 4.8),
    link: darkenTo(p.signal, LIGHT.background, 6.5),
    heat: darkenTo(p.heat, LIGHT.background, 4.8),
  }
  return { dark, light }
}

/** The code colours: one genre colour per kind of token. */
export function tokens() {
  const dark = {
    keyword: lightenTo(CP_COLORS.magenta, DARK.code, 5.5),
    string: lightenTo(CP_COLORS.green, DARK.code, 5.5),
    number: lightenTo(CP_COLORS.orange, DARK.code, 5.5),
    type: lightenTo(CP_COLORS.yellow, DARK.code, 5.5),
    func: lightenTo(CP_COLORS.cyan, DARK.code, 5.5),
    attr: lightenTo(CP_COLORS.violet, DARK.code, 5.5),
    tag: lightenTo(CP_COLORS.blue, DARK.code, 5.5),
    error: lightenTo(CP_COLORS.red, DARK.code, 5.5),
  }
  const light = {
    keyword: darkenTo(CP_COLORS.magenta, LIGHT.code, 4.8),
    string: darkenTo(CP_COLORS.green, LIGHT.code, 4.8),
    number: darkenTo(CP_COLORS.orange, LIGHT.code, 4.8),
    type: darkenTo(CP_COLORS.yellow, LIGHT.code, 4.8),
    func: darkenTo(CP_COLORS.cyan, LIGHT.code, 4.8),
    attr: darkenTo(CP_COLORS.violet, LIGHT.code, 4.8),
    tag: darkenTo(CP_COLORS.blue, LIGHT.code, 4.8),
    error: darkenTo(CP_COLORS.red, LIGHT.code, 4.8),
  }
  return { dark, light }
}

const lines = (rows: [string, string][], pad = "  ") => rows.map(([k, v]) => `${pad}${k}: ${v};`).join("\n")

export function paletteCss(): string {
  const t = tokens()
  const out: string[] = []
  out.push("/* GENERATED by `npm run build:palettes` from lib/scene/palettes.ts. Do not edit by hand. */\n")

  const genre = (mode: "dark" | "light") =>
    CP_COLOR_NAMES.map((n) => [`--c-${n}`, mode === "dark" ? CP_COLORS[n] : darkenTo(CP_COLORS[n], LIGHT.background, 4.5)] as [string, string])
  const tok = (mode: "dark" | "light") => (Object.entries(t[mode]) as [string, string][]).map(([k, v]) => [`--tok-${k}`, v] as [string, string])

  out.push(":root {\n" + lines([...genre("light"), ...tok("light")]) + "\n}\n")
  out.push(".dark {\n" + lines([...genre("dark"), ...tok("dark")]) + "\n}\n")

  for (const p of PALETTES.slice(1)) {
    const r = resolve(p)
    const s = r.dark.surfaces
    out.push(`/* ${p.name}: ${p.note} */`)
    out.push(
      `html.dark[data-palette="${p.id}"] {\n` +
        lines([
          ["--primary", p.primary],
          ["--primary-foreground", INK],
          ["--destructive", r.dark.heat],
          ["--ring", p.signal],
          ["--sidebar-primary", p.primary],
          ["--sidebar-primary-foreground", INK],
          ["--sidebar-ring", p.signal],
          ["--marker", p.primary],
          ["--signal", r.dark.signal],
          ["--heat", r.dark.heat],
          ["--link", r.dark.link],
          ["--muted-foreground", r.dark.mutedForeground],
          ["--grid", r.dark.grid],
          ["--wash-a", rgba(p.heat, 0.09)],
          ["--wash-b", rgba(p.signal, 0.085)],
          ["--glow", rgba(p.signal, 0.32)],
          ["--selection", rgba(p.signal, 0.3)],
          ...(Object.keys(s) as (keyof typeof s)[]).map((k) => [`--${k}`, s[k]] as [string, string]),
        ]) +
        "\n}\n"
    )
    out.push(
      `html:not(.dark)[data-palette="${p.id}"] {\n` +
        lines([
          ["--primary-foreground", p.primary],
          ["--sidebar-primary-foreground", p.primary],
          ["--destructive", r.light.heat],
          ["--ring", r.light.signal],
          ["--sidebar-ring", r.light.signal],
          ["--marker", p.primary],
          ["--signal", r.light.signal],
          ["--heat", r.light.heat],
          ["--link", r.light.link],
          ["--wash-a", rgba(p.heat, 0.045)],
          ["--wash-b", rgba(r.light.signal, 0.07)],
          ["--glow", rgba(r.light.signal, 0.18)],
          ["--selection", rgba(r.light.signal, 0.24)],
        ]) +
        "\n}\n"
    )
  }
  return out.join("\n")
}

/** Used by the test: the lowest contrast any theme lets a text colour fall to. */
export function worstContrast(): number {
  let worst = 21
  for (const p of PALETTES) {
    const r = resolve(p)
    const bg = p.id === "night-city" ? DARK.background : r.dark.surfaces.background
    worst = Math.min(worst, contrast(r.dark.signal, bg), contrast(r.dark.link, bg))
  }
  return worst
}
